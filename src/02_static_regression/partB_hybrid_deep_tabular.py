def numeric(s):
    return pd.to_numeric(s, errors="coerce")


def make_male(d):
    if "male" in d:
        v = numeric(d["male"])
        if set(v.dropna().unique()).issubset({0, 1}):
            return v
    if "sex" not in d:
        raise ValueError("scan_table.csv needs 'male' or 'sex'.")
    s = d["sex"]
    if pd.api.types.is_numeric_dtype(s):
        v = numeric(s)
        if set(v.dropna().unique()).issubset({0, 1}):
            return v
        return v.map({1: 1, 2: 0})
    return s.astype(str).str.strip().str.lower().map({"m": 1, "male": 1, "1": 1, "f": 0, "female": 0, "2": 0})


def load_cohort(scans_path, rich_path):
    if not os.path.isfile(scans_path):
        raise FileNotFoundError(f"Cannot find scan table: {scans_path}")
    d = pd.read_csv(scans_path, low_memory=False)
    req = ["PTID", "Image_ID"] + TARGETS + ["age", "e4"]
    miss = [x for x in req if x not in d]
    if miss:
        raise ValueError(f"Missing columns in scan_table.csv: {miss}")
    d["PTID"] = d["PTID"].astype(str).str.strip()
    d["Image_ID"] = d["Image_ID"].astype(str).str.strip()
    if os.path.isfile(rich_path):
        r = pd.read_csv(rich_path, low_memory=False)
        if "Image_ID" not in r:
            raise ValueError("richer_features.csv must contain Image_ID.")
        r["Image_ID"] = r["Image_ID"].astype(str).str.strip()
        if r["Image_ID"].duplicated().any():
            raise ValueError("Duplicate Image_ID in richer_features.csv; fix before merge.")
        rc = [x for x in r.columns if x != "Image_ID"]
        d = d.merge(r, on="Image_ID", how="left", suffixes=("", "__rich"), validate="many_to_one")
        for c in rc:
            if c + "__rich" in d:
                d[c] = d[c + "__rich"]
                d.drop(columns=[c + "__rich"], inplace=True)
        print(f"Merged {len(rc)} rich feature columns.")
    d["age"] = numeric(d["age"])
    d["male"] = make_male(d)
    d["e4"] = numeric(d["e4"]).clip(0, 2)
    if "edu" in d:
        d["edu"] = numeric(d["edu"])
    for t in TARGETS:
        d[t] = numeric(d[t])
    d = d.dropna(subset=["PTID", "Image_ID", "age", "male", "e4"] + TARGETS).copy()
    if "EXAMDATE" in d:
        d["EXAMDATE"] = pd.to_datetime(d["EXAMDATE"], errors="coerce")
        d = d.sort_values(["PTID", "EXAMDATE", "Image_ID"], kind="mergesort")
    else:
        d = d.sort_values(["PTID", "Image_ID"], kind="mergesort")
    nscans = len(d)
    d = d.groupby("PTID", sort=False, as_index=False).head(1).reset_index(drop=True)
    print(f"Baseline cohort: {nscans} scans -> {len(d)} participants (earliest scan/PTID).")
    return d


def merge_surface_features(d, path):
    if not path:
        return d
    if not os.path.isfile(path):
        raise FileNotFoundError(f"Surface feature table not found: {path}")
    sf = pd.read_csv(path, low_memory=False)
    if "Image_ID" not in sf:
        raise ValueError("Surface feature table must contain Image_ID.")
    sf["Image_ID"] = sf.Image_ID.astype(str).str.strip()
    if sf.Image_ID.duplicated().any():
        raise ValueError("Surface feature table must have one row per Image_ID.")
    cols = [c for c in sf.columns if c != "Image_ID"]
    d = d.merge(sf, on="Image_ID", how="left", suffixes=("", "__surface"), validate="one_to_one")
    for c in cols:
        if c + "__surface" in d:
            d[c] = d[c + "__surface"]
            d.drop(columns=[c + "__surface"], inplace=True)
    print(f"Merged {len(cols)} cortical surface columns from {path}.")
    return d


def build_tab_columns(d, include_mednet=False):
    # Fold-safe models receive raw columns; all imputation/scaling/PCA occurs in sklearn pipelines.
    regular = [c for c in ["age", "male", "edu", "e4", "f_1536", "f_1537"] if c in d]
    regular += [c for c in d.columns if c.startswith(("nv_", "asym_", "hip_", "ent_", "av_", "sym_", "surf_", "ucsf_"))]
    icv = next((c for c in ["icv_proxy", "ucsf_icv", "icv"] if c in d), None)
    if icv:
        den = numeric(d[icv]).replace(0, np.nan)
        for c in [x for x in d.columns if re.fullmatch(r"vol_\d+", x)]:
            av = "av_" + c[4:]
            if av not in d:
                d[av] = numeric(d[c]) / den * 1e3
            regular.append(av)
    # Derived a priori ratios; no outcome or diagnosis information used.
    if all(c in d for c in ["nv_hippocampus", "nv_lateral_ventricle"]):
        d["sym_hip_vent"] = numeric(d["nv_hippocampus"]) / (numeric(d["nv_lateral_ventricle"]) + 1e-6)
        regular.append("sym_hip_vent")
    if all(c in d for c in ["nv_hippocampus", "nv_amygdala", "nv_entorhinal", "nv_parahippocampal"]):
        d["sym_mtl"] = d[["nv_hippocampus", "nv_amygdala", "nv_entorhinal", "nv_parahippocampal"]].sum(axis=1)
        regular.append("sym_mtl")
    if "sym_mtl" in d and "nv_lateral_ventricle" in d:
        d["sym_mtl_vent"] = d["sym_mtl"] / (numeric(d["nv_lateral_ventricle"]) + 1e-6)
        regular.append("sym_mtl_vent")
    mednet = []
    if include_mednet:
        mednet = [c for c in d.columns if re.fullmatch(r"f_\d+", c) and int(c.split("_")[1]) <= 1535]
    banned = set(TARGETS + ["PTID", "Image_ID", "EXAMDATE", "dx", "DX", "scan_idx", "uid", "Subject_ID", "age_at_scan"])
    def keep(cols):
        # Predictor membership is defined from known source columns, not from
        # full-cohort variance/missingness. Fold-specific imputers/scalers handle
        # empty or constant training-fold columns without inspecting test folds.
        out = []
        for c in list(dict.fromkeys(cols)):
            if c in d and c not in banned:
                d[c] = numeric(d[c])
                out.append(c)
        return out
    regular = keep(regular)
    mednet = keep(mednet)
    # Optional mednet columns must not be duplicated in regular branch.
    regular = [c for c in regular if c not in mednet]
    if not regular and not mednet:
        raise ValueError("No tabular features found in scan_table/richer_features.")
    return regular, mednet


def make_preprocessor(regular_cols, mednet_cols, n_mednet_pca):
    transforms = []
    if regular_cols:
        transforms.append(("regular", Pipeline([
            ("impute", SimpleImputer(strategy="median", keep_empty_features=True)),
            ("scale", StandardScaler()),
        ]), regular_cols))
    if mednet_cols:
        transforms.append(("mednet", Pipeline([
            ("impute", SimpleImputer(strategy="median", keep_empty_features=True)),
            ("scale", StandardScaler()),
            ("pca", PCA(n_components=n_mednet_pca, random_state=0)),
        ]), mednet_cols))
    return ColumnTransformer(transforms, remainder="drop", sparse_threshold=0.0)


def model_defs(name, seed, quick):
    if name == "ridge":
        return Ridge(), {"model__alpha": [1.0, 10.0] if quick else [0.1, 1.0, 10.0, 100.0, 300.0]}
    if name == "extratrees":
        return ExtraTreesRegressor(n_estimators=60 if quick else 250, random_state=seed, n_jobs=1), (
            {"model__min_samples_leaf": [3], "model__max_features": [0.8]} if quick else
            {"model__min_samples_leaf": [2, 3, 5], "model__max_features": [0.6, 0.9, 1.0]})
    if name == "histgb":
        return HistGradientBoostingRegressor(random_state=seed, early_stopping=False), (
            {"model__max_iter": [60], "model__max_leaf_nodes": [5], "model__l2_regularization": [1.0]} if quick else
            {"model__max_iter": [80, 140], "model__max_leaf_nodes": [5, 10], "model__l2_regularization": [1.0, 5.0]})
    raise ValueError(name)


def fit_tabular_oof(d, groups, fold_ids, regular_cols, mednet_cols, args, prefix="tab", y_override=None):
    X = d[regular_cols + mednet_cols]
    y = d[TARGETS].to_numpy(float) if y_override is None else np.asarray(y_override, float)
    preds = {f"{prefix}_{m}": np.full_like(y, np.nan, dtype=float) for m in ["ridge", "extratrees", "histgb"]}
    choices = []
    for fold in sorted(np.unique(fold_ids)):
        te = np.where(fold_ids == fold)[0]
        tr = np.where(fold_ids != fold)[0]
        inner_n = min(args.inner_folds, len(np.unique(groups[tr])))
        if inner_n < 2:
            raise ValueError("Need at least two training groups for inner tuning.")
        # Keep PCA dimension below the smallest inner-training sample count.
        min_inner_train = min(len(a) for a, _ in GroupKFold(n_splits=inner_n).split(X.iloc[tr], groups=groups[tr]))
        ncomp = min(args.mednet_pca, max(1, min_inner_train-1), len(mednet_cols)) if mednet_cols else 0
        pre = make_preprocessor(regular_cols, mednet_cols, ncomp)
        for model in ["ridge", "extratrees", "histgb"]:
            for j, t in enumerate(TARGETS):
                est, grid = model_defs(model, args.seed + int(fold)*13 + j, args.quick)
                pipe = Pipeline([("prep", pre), ("model", est)])
                cv = GroupKFold(n_splits=inner_n)
                gs = GridSearchCV(pipe, grid, scoring="neg_mean_squared_error", cv=cv, n_jobs=1, refit=True)
                gs.fit(X.iloc[tr], y[tr, j], groups=groups[tr])
                preds[f"{prefix}_{model}"][te, j] = gs.predict(X.iloc[te])
                choices.append({"fold": int(fold), "model": model, "endpoint": LABELS[t], "best_params": json.dumps(gs.best_params_, default=str)})
        print(f"[Part B tabular] completed fold {fold}", flush=True)
    return preds, choices


def fit_simplex(P, y, penalty=0.02):
    P, y = np.asarray(P, float), np.asarray(y, float)
    ok = np.isfinite(y) & np.isfinite(P).all(1)
    P, y = P[ok], y[ok]
    m = P.shape[1]
    uniform = np.ones(m)/m
    if len(y) < max(10, m+3):
        return uniform
    ys = np.std(y) + 1e-8
    def obj(w):
        return np.mean((P@w-y)**2)/(ys**2) + penalty*np.sum((w-uniform)**2)
    res = minimize(obj, uniform, method="SLSQP", bounds=[(0,1)]*m,
                   constraints=[{"type":"eq", "fun":lambda w:w.sum()-1}],
                   options={"maxiter":500,"ftol":1e-10})
    if not res.success or not np.isfinite(res.x).all():
        return uniform
    return res.x/res.x.sum()


def detect_s16_prediction_columns(df):
    mapping = {}
    suffix_to_target = {"MMSE":"MMSCORE", "CDR-SB":"CDRSB", "ADAS-Cog13":"TOTAL13"}
    for c in df.columns:
        m = re.match(r"(.+)__pred_(MMSE|CDR-SB|ADAS-Cog13)$", c)
        if m:
            model, outcome = m.group(1), m.group(2)
            mapping.setdefault(model, {})[suffix_to_target[outcome]] = c
    # The requested late-fusion candidates are the existing deep models only.
    # S16 may also save its own tabular predictions; Part B refits tabular OOF
    # models on the exact same fold map, so do not double-count those columns.
    return {m: cols for m, cols in mapping.items()
            if len(cols) == 3 and any(tok in m.lower() for tok in ("film", "vit", "gat"))}


def load_s16_oof(path, cohort_ptids, fold_map_path=""):
    if not path:
        return None, None
    if not os.path.isfile(path):
        raise FileNotFoundError(f"S16 OOF file not found: {path}")
    s = pd.read_csv(path, low_memory=False)
    if "PTID" not in s:
        raise ValueError("S16 OOF file must have a PTID column.")
    s["PTID"] = s["PTID"].astype(str).str.strip()
    if s["PTID"].duplicated().any():
        raise ValueError("S16 OOF must be one row per PTID. It appears to contain repeated rows.")
    models = detect_s16_prediction_columns(s)
    if not models:
        raise ValueError("No complete S16 model prediction triplets found. Expected <model>__pred_MMSE/CDR-SB/ADAS-Cog13.")
    if "outer_fold" not in s.columns:
        candidate = fold_map_path or str(Path(path).with_name("S16_outer_folds.csv"))
        if not os.path.isfile(candidate):
            raise ValueError("S16 OOF has no outer_fold column. Pass --fold-map S16_outer_folds.csv.")
        fm = pd.read_csv(candidate, low_memory=False)
        if not {"PTID", "outer_fold"}.issubset(fm.columns):
            raise ValueError("Fold map needs PTID and outer_fold columns.")
        fm["PTID"] = fm.PTID.astype(str).str.strip()
        if fm.PTID.duplicated().any():
            raise ValueError("Fold map must contain one outer_fold per PTID.")
        s = s.merge(fm[["PTID", "outer_fold"]], on="PTID", how="left", validate="one_to_one")
    if s["outer_fold"].isna().any():
        raise ValueError("Some S16 OOF participants have no outer_fold mapping.")
    # The common cohort is the intersection of scan table and S16 OOF participants.
    # The caller will restrict all arms to this exact matched participant set.
    keep = set(cohort_ptids)
    s = s[s.PTID.isin(keep)].copy()
    if s.PTID.duplicated().any():
        raise ValueError("S16 OOF PTIDs are not unique after filtering.")
    print(f"Loaded S16 OOF: models={list(models)}, folds={sorted(s.outer_fold.unique())}, matched participants={len(s)}.")
    return s, models

def load_nested_s16(path, cohort_ptids):
    """Expected one row per (PTID, eval_outer_fold), with fold-specific deep predictions.

    For each eval_outer_fold=f, predictions for PTIDs outside f must be generated
    by inner cross-fitting using ONLY participants outside f. Predictions for
    PTIDs in f must be generated by a model trained ONLY on participants outside f.
    """
    if not path:
        return None, None
    z = pd.read_csv(path, low_memory=False)
    need = {"PTID", "eval_outer_fold"}
    if not need.issubset(z.columns):
        raise ValueError("Nested S16 OOF needs PTID and eval_outer_fold.")
    z["PTID"] = z.PTID.astype(str).str.strip()
    models = detect_s16_prediction_columns(z)
    if not models:
        raise ValueError("No model prediction columns found in nested S16 OOF.")
    z = z[z.PTID.isin(set(cohort_ptids))].copy()
    if z.duplicated(["PTID", "eval_outer_fold"]).any():
        raise ValueError("Duplicate (PTID, eval_outer_fold) rows in nested S16 file.")
    for fold in z.eval_outer_fold.unique():
        pts = set(z.loc[z.eval_outer_fold == fold, "PTID"])
        if pts != set(cohort_ptids):
            raise ValueError(f"Nested S16 file for eval fold {fold} must contain every cohort PTID exactly once.")
    return z, models


def fit_fixed_tab_model(X_train, y_train, X_predict, model_name, seed,
                        regular_cols, mednet_cols, args):
    """Pre-specified, non-tuned base learner used for fold-conditional stacking.

    Imputation, scaling and optional MedicalNet PCA are fitted only on X_train.
    Fixed learner parameters avoid allowing an inner held-out participant to
    influence hyperparameter selection for the meta-training prediction.
    """
    ncomp = min(args.mednet_pca, max(1, len(X_train)-1), len(mednet_cols)) if mednet_cols else 0
    prep = make_preprocessor(regular_cols, mednet_cols, ncomp)
    if model_name == "ridge":
        est = Ridge(alpha=10.0)
    elif model_name == "extratrees":
        est = ExtraTreesRegressor(n_estimators=250, min_samples_leaf=3,
                                  max_features=0.8, random_state=seed, n_jobs=1)
    elif model_name == "histgb":
        est = HistGradientBoostingRegressor(max_iter=120, max_leaf_nodes=7,
                                             l2_regularization=2.0, random_state=seed,
                                             early_stopping=False)
    else:
        raise ValueError(model_name)
    pipe = Pipeline([("prep", prep), ("model", est)])
    pipe.fit(X_train, y_train)
    return pipe.predict(X_predict)

def build_fold_conditional_tabular_predictions(d, groups, fold_ids, y, regular_cols, mednet_cols, args):
    """Return predictions for every (evaluation fold, participant, model, outcome).

    For evaluation fold f, each outer-training participant's tabular prediction is
    generated by a fixed-parameter model trained on other outer-training participants
    (inner cross-fitting). The f-fold predictions come from a model trained only on
    the outer-training participants. This prevents fold f targets entering the meta-
    training predictions used to fit f's blend weights.
    """
    X = d[regular_cols + mednet_cols]
    all_models = ["ridge", "extratrees", "histgb"]
    result = {}
    for eval_fold in sorted(np.unique(fold_ids)):
        outer_tr = np.where(fold_ids != eval_fold)[0]
        outer_te = np.where(fold_ids == eval_fold)[0]
        inner_k = min(args.inner_folds, len(np.unique(groups[outer_tr])))
        if inner_k < 2:
            raise ValueError("Not enough groups for fold-conditional tabular cross-fitting.")
        conditional = {m: np.full((len(d), 3), np.nan, dtype=float) for m in all_models}
        gkf = GroupKFold(n_splits=inner_k)
        # Cross-fitted predictions for the outer-training subjects.
        for i_tr_local, i_va_local in gkf.split(outer_tr, groups=groups[outer_tr]):
            it = outer_tr[i_tr_local]
            iv = outer_tr[i_va_local]
            for m in all_models:
                for j in range(3):
                    conditional[m][iv, j] = fit_fixed_tab_model(
                        X.iloc[it], y[it, j], X.iloc[iv], m,
                        args.seed + int(eval_fold)*1009 + len(it) + j, regular_cols, mednet_cols, args)
        # Outer evaluation predictions: train on all outer-training subjects.
        for m in all_models:
            for j in range(3):
                conditional[m][outer_te, j] = fit_fixed_tab_model(
                    X.iloc[outer_tr], y[outer_tr, j], X.iloc[outer_te], m,
                    args.seed + int(eval_fold)*2017 + j, regular_cols, mednet_cols, args)
        result[int(eval_fold)] = conditional
        print(f"[B1 strict tabular cross-fit] evaluation fold {eval_fold} complete", flush=True)
    return result


def lofo_late_fusion(df, fold_ids, s16_df, s16_models, tab_preds, args,
                     nested_df=None, nested_models=None, nested_tab=None):
    """LOFO blending. Strict mode needs both nested S16 predictions and nested tab predictions."""
    y = df[TARGETS].to_numpy(float)
    pred = np.full_like(y, np.nan, dtype=float)
    rows_weights = []
    for j, target in enumerate(TARGETS):
        for fold in sorted(np.unique(fold_ids)):
            te = np.where(fold_ids == fold)[0]
            tr = np.where(fold_ids != fold)[0]
            if nested_df is not None:
                part = nested_df[nested_df.eval_outer_fold == fold].set_index("PTID").loc[df.PTID.astype(str)].reset_index()
                P_deep = [part[cols[target]].to_numpy(float) for cols in nested_models.values()]
                P_tab = [nested_tab[int(fold)][m][:, j] for m in ["ridge", "extratrees", "histgb"]]
                names = [f"S16_{m}" for m in nested_models] + [f"tab_{m}_nested" for m in ["ridge", "extratrees", "histgb"]]
                P = np.column_stack(P_deep + P_tab)
            else:
                P_deep = [s16_df[cols[target]].to_numpy(float) for cols in s16_models.values()]
                P_tab = [tab_preds[m][:, j] for m in tab_preds]
                names = [f"S16_{m}" for m in s16_models] + list(tab_preds)
                P = np.column_stack(P_deep + P_tab)
            w = fit_simplex(P[tr], y[tr, j], penalty=0.03)
            pred[te, j] = P[te] @ w
            for nm, ww in zip(names, w):
                rows_weights.append({"outer_fold": int(fold), "endpoint": LABELS[target], "model": nm,
                                     "weight": float(ww), "weight_fit_n": len(tr),
                                     "nested_predictions": nested_df is not None})
    return pred, pd.DataFrame(rows_weights)

def build_roi_paths(df, root, seg_name, t1_name):
    root = Path(root)
    if not root.is_dir():
        raise FileNotFoundError(f"FastSurfer image root does not exist: {root}")
    out = {}
    for image_id in df.Image_ID.astype(str):
        subj = root / image_id
        candidates = [
            (subj / "mri" / seg_name, subj / "mri" / t1_name),
            (subj / seg_name, subj / t1_name),
        ]
        pair = next(((a, b) for a, b in candidates if a.is_file() and b.is_file()), None)
        if pair is None:
            # More flexible recursive search constrained to exact subject directory.
            if subj.is_dir():
                segs = list(subj.rglob(seg_name)); t1s = list(subj.rglob(t1_name))
                if segs and t1s:
                    pair = (segs[0], t1s[0])
        if pair:
            out[image_id] = (str(pair[0]), str(pair[1]))
    return out


def extract_roi(seg_path, t1_path, roi_size):
    import nibabel as nib
    from nibabel.processing import resample_from_to
    from scipy.ndimage import zoom
    s_img = nib.load(seg_path)
    t_img = nib.load(t1_path)
    if t_img.shape[:3] != s_img.shape[:3] or not np.allclose(t_img.affine, s_img.affine, atol=1e-3):
        t_img = resample_from_to(t_img, s_img, order=1)
    seg = np.asanyarray(s_img.dataobj).astype(np.int32)
    t1 = np.asanyarray(t_img.dataobj).astype(np.float32)
    masks = {
        "hip": np.isin(seg, [17, 53]),
        "amy": np.isin(seg, [18, 54]),
        "ent": np.isin(seg, [1006, 2006]),
        "para": np.isin(seg, [1016, 2016]),
    }
    union = np.logical_or.reduce(list(masks.values()))
    if int(union.sum()) < 80:
        raise ValueError("Fewer than 80 voxels in medial-temporal ROI; check DKT label IDs / segmentation.")
    coords = np.where(union)
    pad = 8
    lo = [max(0, int(c.min()) - pad) for c in coords]
    hi = [min(seg.shape[i], int(coords[i].max()) + 1 + pad) for i in range(3)]
    sl = tuple(slice(lo[i], hi[i]) for i in range(3))
    t = t1[sl].copy()
    roi = {k: v[sl].astype(np.float32) for k, v in masks.items()}
    u = union[sl]
    vals = t[u]
    q1, q99 = np.percentile(vals, [1, 99])
    t = np.clip(t, q1, q99)
    mu, sd = float(t[u].mean()), float(t[u].std())
    t = np.clip((t-mu)/(sd+1e-6), -5, 5).astype(np.float32)
    side = int(max(t.shape))
    def to_cube(a, is_mask=False):
        pads = []
        for dim in a.shape:
            total = side-dim
            pads.append((total//2, total-total//2))
        a = np.pad(a, pads, mode="constant")
        a = zoom(a, [roi_size/side]*3, order=0 if is_mask else 1)
        out = np.zeros((roi_size, roi_size, roi_size), dtype=np.float32)
        ss = tuple(slice(0, min(roi_size, a.shape[i])) for i in range(3))
        out[ss] = a[ss].astype(np.float32)
        return out
    return np.stack([to_cube(t)] + [to_cube(roi[k], True) for k in ["hip", "amy", "ent", "para"]]).astype(np.float32)


def prepare_roi_cache(df, root, seg_name, t1_name, cache_dir, roi_size):
    cache = Path(cache_dir)
    cache.mkdir(parents=True, exist_ok=True)
    paths_found = build_roi_paths(df, root, seg_name, t1_name)
    final_paths = [None]*len(df)
    fails = []
    for i, row in df.iterrows():
        iid = str(row.Image_ID)
        if iid not in paths_found:
            fails.append({"PTID": row.PTID, "Image_ID": iid, "reason": "missing segmentation or T1"})
            continue
        out = cache / f"{re.sub(r'[^A-Za-z0-9_-]', '_', iid)}_{roi_size}.npy"
        try:
            if not out.exists():
                arr = extract_roi(paths_found[iid][0], paths_found[iid][1], roi_size)
                np.save(out, arr)
            final_paths[i] = str(out)
        except Exception as e:
            fails.append({"PTID": row.PTID, "Image_ID": iid, "reason": str(e)})
    pd.DataFrame(fails).to_csv(cache / "missing_or_failed_scans.csv", index=False)
    ok = np.array([x is not None for x in final_paths])
    print(f"ROI cache: {int(ok.sum())}/{len(df)} participants usable; failures saved to {cache/'missing_or_failed_scans.csv'}.")
    return final_paths, ok


def make_es_split(groups, seed, val_fraction=0.18):
    unique = np.unique(groups)
    if len(unique) < 4:
        raise ValueError("Too few training participants for a separate early-stopping validation split.")
    rng = np.random.RandomState(seed)
    u = rng.permutation(unique)
    nv = max(1, int(round(len(u)*val_fraction)))
    val_groups = set(u[:nv])
    val = np.array([g in val_groups for g in groups])
    return np.where(~val)[0], np.where(val)[0]


def create_film_resnet():
    import torch
    import torch.nn as nn

    class Block(nn.Module):
        def __init__(self, cin, cout, stride=1):
            super().__init__()
            self.conv1 = nn.Conv3d(cin, cout, 3, stride=stride, padding=1, bias=False)
            self.norm1 = nn.GroupNorm(4, cout)
            self.conv2 = nn.Conv3d(cout, cout, 3, padding=1, bias=False)
            self.norm2 = nn.GroupNorm(4, cout)
            self.skip = nn.Identity() if cin == cout and stride == 1 else nn.Sequential(
                nn.Conv3d(cin, cout, 1, stride=stride, bias=False), nn.GroupNorm(4, cout))
            self.act = nn.GELU()
        def forward(self, x):
            z = self.act(self.norm1(self.conv1(x)))
            z = self.norm2(self.conv2(z))
            return self.act(z+self.skip(x))

    class FilmResNet(nn.Module):
        def __init__(self, cond_dim=4, nout=3):
            super().__init__()
            self.stem = nn.Sequential(nn.Conv3d(5, 8, 5, stride=2, padding=2, bias=False),
                                       nn.GroupNorm(4, 8), nn.GELU(), nn.MaxPool3d(2))
            self.b1 = nn.Sequential(Block(8, 8), Block(8, 8))
            self.b2 = nn.Sequential(Block(8, 16, 2), Block(16, 16))
            self.b3 = nn.Sequential(Block(16, 32, 2), Block(32, 32))
            self.b4 = nn.Sequential(Block(32, 48, 2), Block(48, 48))
            self.cond = nn.Sequential(nn.Linear(cond_dim, 16), nn.GELU(), nn.Dropout(0.1))
            self.film = nn.Linear(16, 96)
            self.head = nn.Sequential(nn.Linear(48+16, 48), nn.GELU(), nn.Dropout(0.3), nn.Linear(48, nout))
        def encode(self, x, c):
            c = self.cond(c)
            x = self.stem(x); x = self.b1(x); x = self.b2(x); x = self.b3(x); x = self.b4(x)
            z = x.mean(dim=(2,3,4))
            gamma, beta = self.film(c).chunk(2, dim=1)
            z = z*(1+gamma)+beta
            return torch.cat([z, c], dim=1)
        def forward(self, x, c):
            return self.head(self.encode(x, c))
    return FilmResNet


def train_encoder_and_embed(paths, cond_raw, y_raw, groups, fit_ids, val_ids, embed_ids,
                            args, device, seed):
    """Train only on fit_ids, early-stop on val_ids, return embeddings for embed_ids."""
    import torch
    from torch.utils.data import Dataset, DataLoader
    torch.manual_seed(seed); np.random.seed(seed); random.seed(seed)
    model_cls = create_film_resnet()
    fit_ids = np.asarray(fit_ids, int); val_ids = np.asarray(val_ids, int); embed_ids = np.asarray(embed_ids, int)
    c_fit = cond_raw[fit_ids].astype(np.float32)
    c_mu = np.nanmean(c_fit, axis=0)
    c_mu[~np.isfinite(c_mu)] = 0.0
    c_sd = np.nanstd(c_fit, axis=0); c_sd[~np.isfinite(c_sd) | (c_sd < 1e-6)] = 1.0
    c_all = (np.where(np.isfinite(cond_raw), cond_raw, c_mu)-c_mu)/c_sd
    y_fit = y_raw[fit_ids].astype(np.float32)
    y_mu = y_fit.mean(0); y_sd = y_fit.std(0); y_sd[y_sd < 1e-6] = 1.0
    # Only fill targets for gradient-training and early-stopping participants.
    # embed_ids (especially the outer test fold) are not read/transformed as labels.
    y_all = np.zeros_like(y_raw, dtype=np.float32)
    used_ids = np.unique(np.concatenate([fit_ids, val_ids]))
    y_all[used_ids] = (y_raw[used_ids]-y_mu)/y_sd

    class MRISet(Dataset):
        def __init__(self, ids, with_y): self.ids=np.asarray(ids,int); self.with_y=with_y
        def __len__(self): return len(self.ids)
        def __getitem__(self, k):
            ix=int(self.ids[k]); x=np.load(paths[ix], mmap_mode="r").astype(np.float32,copy=False)
            xx=torch.from_numpy(np.array(x,copy=True)); cc=torch.from_numpy(c_all[ix].astype(np.float32))
            if self.with_y: return xx,cc,torch.from_numpy(y_all[ix].astype(np.float32))
            return xx,cc
    pin = device.type == "cuda"
    fit_loader = DataLoader(MRISet(fit_ids,True),batch_size=args.batch_size,shuffle=True,num_workers=0,pin_memory=pin)
    val_loader = DataLoader(MRISet(val_ids,True),batch_size=args.batch_size,shuffle=False,num_workers=0,pin_memory=pin)
    model = model_cls(cond_dim=cond_raw.shape[1]).to(device)
    opt = torch.optim.AdamW(model.parameters(),lr=args.lr,weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(opt,mode="min",factor=0.5,patience=3)
    loss_fn = torch.nn.SmoothL1Loss(beta=1.0)
    max_epochs = args.epochs
    best_loss=float("inf"); best_state=None; best_epoch=1; wait=0
    for epoch in range(max_epochs):
        model.train(); losses=[]
        for xb,cb,yb in fit_loader:
            xb,cb,yb=xb.to(device),cb.to(device),yb.to(device)
            opt.zero_grad(set_to_none=True); pr=model(xb,cb); loss=loss_fn(pr,yb); loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(),1.0); opt.step(); losses.append(float(loss.detach().cpu()))
        model.eval(); vl=[]
        with torch.no_grad():
            for xb,cb,yb in val_loader:
                pr=model(xb.to(device),cb.to(device)); vl.append(float(loss_fn(pr,yb.to(device)).detach().cpu()))
        score=float(np.mean(vl)) if vl else float(np.mean(losses)); scheduler.step(score)
        if score < best_loss-1e-5:
            best_loss=score; best_epoch=epoch+1; best_state=copy.deepcopy(model.state_dict()); wait=0
        else:
            wait += 1
            if wait >= args.patience: break
    if best_state is not None: model.load_state_dict(best_state)
    # Embeddings are produced from the model trained only on fit_ids; val_ids and embed_ids
    # were never used for gradient updates. For cross-fitted train embeddings, embed_ids is
    # a held-out inner fold. For outer test embeddings, embed_ids is the outer test fold.
    model.eval(); embed_loader=DataLoader(MRISet(embed_ids,False),batch_size=args.batch_size,shuffle=False,num_workers=0,pin_memory=pin)
    emb=[]
    with torch.no_grad():
        for xb,cb in embed_loader:
            zz=model.encode(xb.to(device),cb.to(device)).cpu().numpy(); emb.append(zz)
    out=np.concatenate(emb,axis=0) if emb else np.empty((0,64),np.float32)
    del model,opt,fit_loader,val_loader,embed_loader
    if device.type=="cuda": torch.cuda.empty_cache()
    return out, best_epoch, best_loss


def train_outer_fold_embeddings(paths, cond_raw, y_raw, groups, tr, te, args, device, seed):
    """Cross-fit embeddings for outer-train subjects, and separately embed outer test.

    For each inner validation fold, a network is trained on a subset of the remaining
    outer-training subjects and early-stopped on a second disjoint subset. Thus each
    training participant's embedding comes from a network that did not train on them.
    """
    outer_groups = groups[tr]
    k = min(args.inner_folds, len(np.unique(outer_groups)))
    if k < 2: raise ValueError("Too few outer-training groups for cross-fitted embeddings.")
    local = np.arange(len(tr))
    gkf = GroupKFold(n_splits=k)
    emb_train = np.full((len(tr),64),np.nan,np.float32)
    inner_logs=[]
    for ii,(fitloc,embval_loc) in enumerate(gkf.split(local,groups=outer_groups)):
        inner_fit = tr[fitloc]
        inner_emb = tr[embval_loc]
        # Early-stop holdout is selected only from inner_fit (which excludes inner_emb).
        es_fit_loc, es_val_loc = make_es_split(groups[inner_fit], seed+ii*19, val_fraction=0.18)
        fit_ids = inner_fit[es_fit_loc]; val_ids=inner_fit[es_val_loc]
        e, ep, vl = train_encoder_and_embed(paths,cond_raw,y_raw,groups,fit_ids,val_ids,inner_emb,args,device,seed+ii*101)
        emb_train[embval_loc]=e
        inner_logs.append({"inner_fold":ii,"n_fit":len(fit_ids),"n_earlystop_val":len(val_ids),"n_embedded":len(inner_emb),"best_epoch":ep,"best_val_loss":vl})
        print(f"    inner embedding fold {ii+1}/{k}: embedded {len(inner_emb)} held-out training participants (best epoch {ep})",flush=True)
    if not np.isfinite(emb_train).all():
        raise RuntimeError("Some cross-fitted training embeddings are missing.")
    # Final outer-test embeddings: split outer-train for early stopping, but never use outer-test.
    es_fit_loc, es_val_loc = make_es_split(groups[tr],seed+999,val_fraction=0.18)
    fit_ids=tr[es_fit_loc]; val_ids=tr[es_val_loc]
    emb_test, ep, vl=train_encoder_and_embed(paths,cond_raw,y_raw,groups,fit_ids,val_ids,te,args,device,seed+1777)
    return emb_train,emb_test,inner_logs,{"n_fit":len(fit_ids),"n_earlystop_val":len(val_ids),"best_epoch":ep,"best_val_loss":vl}


