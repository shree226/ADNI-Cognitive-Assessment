def zlib_seed(s):
    import zlib
    return zlib.crc32(s.encode("utf-8")) & 0xffffffff


def holm(pvals):
    p=np.asarray(pvals,float); order=np.argsort(p); out=np.empty(len(p)); running=0.0; m=len(p)
    for r,i in enumerate(order): running=max(running,min(1.0,(m-r)*p[i])); out[i]=running
    return out


def paired_deltas(avg,y,baseline,boot,seed):
    if baseline not in avg: baseline=next(iter(avg))
    rng=np.random.RandomState(seed); samples=[rng.randint(0,len(y),len(y)) for _ in range(boot)]
    rows=[]
    for name,p in avg.items():
        if name==baseline: continue
        for j,t in enumerate(TARGETS):
            delta=r2_safe(y[:,j],p[:,j])-r2_safe(y[:,j],avg[baseline][:,j])
            bs=np.array([r2_safe(y[ix,j],p[ix,j])-r2_safe(y[ix,j],avg[baseline][ix,j]) for ix in samples])
            rows.append({"model":name,"baseline":baseline,"endpoint":LABELS[t],"delta_R2":delta,
                         "CI_lo":np.nanpercentile(bs,2.5),"CI_hi":np.nanpercentile(bs,97.5),
                         "p_boot":min(1.0,max(2*min(np.mean(bs<=0),np.mean(bs>=0)),1/(boot+1)))})
        bs=[]
        for ix in samples:
            bs.append(np.mean([r2_safe(y[ix,j],p[ix,j])-r2_safe(y[ix,j],avg[baseline][ix,j]) for j in range(3)]))
        point=np.mean([r2_safe(y[:,j],p[:,j])-r2_safe(y[:,j],avg[baseline][:,j]) for j in range(3)])
        rows.append({"model":name,"baseline":baseline,"endpoint":"MEAN_R2","delta_R2":point,
                     "CI_lo":np.nanpercentile(bs,2.5),"CI_hi":np.nanpercentile(bs,97.5),
                     "p_boot":min(1.0,max(2*min(np.mean(np.asarray(bs)<=0),np.mean(np.asarray(bs)>=0)),1/(boot+1)))})
    out=pd.DataFrame(rows)
    if len(out): out["p_holm"]=holm(out.p_boot.values)
    return out


