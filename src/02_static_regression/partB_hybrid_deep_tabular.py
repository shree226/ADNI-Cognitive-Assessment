"""Part B: hybrid MRI-deep + tabular prediction for ADNI cognitive scores.

B1 late fusion:
  - Fits tabular OOF models on the exact outer_fold assignment from S16.
  - Blends tabular OOF predictions with available S16 OOF predictions.
  - For each evaluated fold, weights are fit using rows from all OTHER folds.

  IMPORTANT LIMITATION: a single conventional S16 OOF table is not sufficient
  to prove fully nested, fold-isolated late fusion. The predictions for the
  non-evaluated folds may have been generated by S16 models whose training sets
  included the evaluated fold. Therefore the LOFO blend excludes held-out-fold
  targets from weight fitting, but may still have indirect cross-fold training
  contamination. It is labelled LEGACY/EXPLORATORY. For publication-grade strict
  late fusion, pass --s16-nested-oof in the documented fold-specific format.

B2 cross-fitted embeddings:
  - Uses one baseline scan/PTID and common outer folds.
  - For each outer fold, creates inner out-of-fold embeddings for outer-training
    participants: no participant is embedded by a network trained on that
    participant's cognitive targets.
  - MRI network early-stopping validation and target/condition normalisation are
    confined to outer-training participants.
  - PCA is fit only on cross-fitted outer-training embeddings.
  - The combined tabular + PCA embedding matrix is then used by Ridge/ExtraTrees.

Example:
  python partB_hybrid_deep_tabular.py --scans scan_table.csv \
      --rich richer_features.csv --s16-oof results_final/S16/S16_oof_predictions.csv \
      --image-root FastSurfer_output_from_HDBET --out-dir results_final/PartB \
      --folds 5 --inner-folds 3 --epochs 30 --batch-size 2 --boot 1000

Quick smoke test:
  python partB_hybrid_deep_tabular.py --scans scan_table.csv \
      --rich richer_features.csv --s16-oof results_final/S16/S16_oof_predictions.csv \
      --image-root FastSurfer_output_from_HDBET --out-dir results_final/PartB_smoke --quick

Permuted-target null (B2 + tabular only; real-target S16 predictions are disabled):
  python partB_hybrid_deep_tabular.py --scans scan_table.csv \
      --rich richer_features.csv --s16-oof results_final/S16/S16_oof_predictions.csv \
      --image-root FastSurfer_output_from_HDBET --out-dir results_final/PartB_null \
      --permute-targets --quick
"""
